"""Write the data dictionary, `docs/data/dictionary.md`, from the declared schemas.

The dictionary is generated, never edited by hand: a test fails when the
committed file differs from what the schemas produce.
"""

from __future__ import annotations

import sys
from typing import Final

from forge.pipeline.lock import FORGE_ROOT
from forge.stages import STAGES
from forge.uniprot.evidence import EVIDENCE_CODES, REVIEW_STATUS
from forge.uniprot.tables import GAP_PHRASES

DICTIONARY: Final = FORGE_ROOT.parent / "docs" / "data" / "dictionary.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    lines = [
        "# Data dictionary",
        "",
        "Generated by `python -m forge dictionary` from the table declarations in `forge/`.",
        "Do not edit by hand: a test fails when this file and the declarations disagree.",
        "",
        "Every column has a **kind** (plan section 4.10): *measured*, *curated*, *predicted* or",
        "*generated*; *per row* where the kind is in the row's `evidence_kind` column;",
        "*identifier* for names of records; *pipeline* for values the Forge itself writes",
        "(hashes, statuses, reasons), which are not claims about biology.",
        "",
        "## Tables",
        "",
        "| Table | Made by stage | Sources | Key | What one row is |",
        "|---|---|---|---|---|",
    ]
    for stage in STAGES:
        for schema in stage.outputs:
            sources = ", ".join(schema.sources) or "none (the Forge's own)"
            lines.append(
                f"| [`{schema.name}`](#{schema.name}) | {stage.name} | {sources} | "
                f"{', '.join(schema.key)} | {_cell(schema.description)} |"
            )
    for stage in STAGES:
        for schema in stage.outputs:
            lines += [
                "",
                f"## {schema.name}",
                "",
                _cell(schema.description),
                "",
                f"Sources: {', '.join(schema.sources) or 'none'}. Key, and sort order: "
                f"{', '.join(f'`{k}`' for k in schema.key)}. Schema fingerprint: "
                f"`{schema.fingerprint()[:16]}`.",
                "",
                "| Column | Type | Null allowed | Kind | Description |",
                "|---|---|---|---|---|",
            ]
            for column in schema.columns:
                lines.append(
                    f"| `{column.name}` | {column.type} | {'yes' if column.nullable else 'no'} | "
                    f"{column.kind} | {_cell(column.description)} |"
                )
    lines += [
        "",
        "## Gaps recorded in `proteins.gaps`",
        "",
        "A protein that lacks something a reader might expect is kept, and the gap is named:",
        "",
        *[
            f"- {phrase.strip()}{'(letters)' if phrase.endswith(': ') else ''}"
            for phrase in GAP_PHRASES
        ],
        "",
        "## Evidence codes and their proposed kinds",
        "",
        f"**Status: {REVIEW_STATUS}.** This mapping is a proposal. Nothing shown to a",
        "reader should depend on it until a biologist has reviewed each line. It is also",
        "released as the table `evidence_codes`.",
        "",
        "Rules: a row with several codes takes the most direct kind among them (measured,",
        "then curated, then predicted). Free text a curator wrote (comments, disease notes)",
        "is never more than curated. A row with no evidence code has no kind (null), and",
        "an evidence code with no proposed kind fails the build.",
        "",
        "| Code | GO code | Assertion | Proposed kind | What it means | Why that kind |",
        "|---|---|---|---|---|---|",
    ]
    for code in EVIDENCE_CODES:
        lines.append(
            f"| {code.code} | {code.go_code or ''} | {code.assertion} | **{code.kind}** | "
            f"{_cell(code.label)} | {_cell(code.rationale)} |"
        )
    return "\n".join(lines) + "\n"


def main(*, check: bool) -> int:
    text = render()
    if check:
        if not DICTIONARY.exists() or DICTIONARY.read_text(encoding="utf-8") != text:
            print(f"{DICTIONARY} is out of date; run python -m forge dictionary", file=sys.stderr)
            return 1
        print(f"{DICTIONARY.name} is up to date")
        return 0
    DICTIONARY.parent.mkdir(parents=True, exist_ok=True)
    DICTIONARY.write_text(text, encoding="utf-8")
    print(f"wrote {DICTIONARY}")
    return 0
